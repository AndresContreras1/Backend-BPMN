-- Esquema inicial del perfil prod (PostgreSQL). Corresponde a las entidades JPA:
-- Hibernate arranca con ddl-auto=validate y falla si una entidad no cuadra con su tabla.
-- Todo dato cuelga de una empresa (empresa_id); los hijos de un proceso se borran con él (ON DELETE CASCADE).

CREATE TABLE empresa (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre          VARCHAR(120) NOT NULL,
    nit             VARCHAR(30)  NOT NULL,
    correo_contacto VARCHAR(120) NOT NULL,
    activo          BOOLEAN      NOT NULL,
    creado_en       TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    modificado_en   TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    creado_por      VARCHAR(120) NOT NULL,
    modificado_por  VARCHAR(120) NOT NULL,
    CONSTRAINT uk_empresa_nit UNIQUE (nit)
);

CREATE TABLE usuarios (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    empresa_id     BIGINT       NOT NULL,
    nombre         VARCHAR(120) NOT NULL,
    correo         VARCHAR(120) NOT NULL,
    password       VARCHAR(100) NOT NULL,
    rol            VARCHAR(20)  NOT NULL,
    activo         BOOLEAN      NOT NULL,
    creado_en      TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    modificado_en  TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    creado_por     VARCHAR(120) NOT NULL,
    modificado_por VARCHAR(120) NOT NULL,
    CONSTRAINT uk_usuario_correo UNIQUE (correo),
    CONSTRAINT ck_usuario_rol CHECK (rol IN ('ADMINISTRADOR', 'EDITOR', 'LECTOR')),
    CONSTRAINT fk_usuario_empresa FOREIGN KEY (empresa_id) REFERENCES empresa (id)
);
CREATE INDEX idx_usuario_empresa ON usuarios (empresa_id);

CREATE TABLE rol_proceso (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    empresa_id     BIGINT       NOT NULL,
    nombre         VARCHAR(80)  NOT NULL,
    descripcion    VARCHAR(300),
    activo         BOOLEAN      NOT NULL,
    creado_en      TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    modificado_en  TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    creado_por     VARCHAR(120) NOT NULL,
    modificado_por VARCHAR(120) NOT NULL,
    CONSTRAINT fk_rol_proceso_empresa FOREIGN KEY (empresa_id) REFERENCES empresa (id)
);
CREATE INDEX idx_rol_proceso_empresa ON rol_proceso (empresa_id);

CREATE TABLE proceso (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    empresa_id     BIGINT       NOT NULL,
    nombre         VARCHAR(120) NOT NULL,
    descripcion    VARCHAR(500),
    categoria      VARCHAR(60)  NOT NULL,
    estado         VARCHAR(20)  NOT NULL,
    activo         BOOLEAN      NOT NULL,
    version        BIGINT,
    creado_en      TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    modificado_en  TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    creado_por     VARCHAR(120) NOT NULL,
    modificado_por VARCHAR(120) NOT NULL,
    CONSTRAINT ck_proceso_estado CHECK (estado IN ('BORRADOR', 'PUBLICADO')),
    CONSTRAINT fk_proceso_empresa FOREIGN KEY (empresa_id) REFERENCES empresa (id)
);
CREATE INDEX idx_proceso_empresa ON proceso (empresa_id);

CREATE TABLE proceso_compartido (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    empresa_id          BIGINT       NOT NULL,
    proceso_id          BIGINT       NOT NULL,
    empresa_invitada_id BIGINT       NOT NULL,
    activo              BOOLEAN      NOT NULL,
    creado_en           TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    modificado_en       TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    creado_por          VARCHAR(120) NOT NULL,
    modificado_por      VARCHAR(120) NOT NULL,
    CONSTRAINT fk_compartido_empresa FOREIGN KEY (empresa_id) REFERENCES empresa (id),
    CONSTRAINT fk_compartido_invitada FOREIGN KEY (empresa_invitada_id) REFERENCES empresa (id),
    CONSTRAINT fk_compartido_proceso FOREIGN KEY (proceso_id) REFERENCES proceso (id) ON DELETE CASCADE
);
CREATE INDEX idx_compartido_proceso ON proceso_compartido (proceso_id);
CREATE INDEX idx_compartido_invitada ON proceso_compartido (empresa_invitada_id);

CREATE TABLE historial_cambio (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    empresa_id     BIGINT        NOT NULL,
    proceso_id     BIGINT,
    usuario_id     BIGINT,
    usuario_correo VARCHAR(120)  NOT NULL,
    fecha          TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    tipo           VARCHAR(20)   NOT NULL,
    elemento       VARCHAR(20)   NOT NULL,
    elemento_id    BIGINT,
    detalle        VARCHAR(1000) NOT NULL,
    advertencias   VARCHAR(2000),
    creado_en      TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    modificado_en  TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    creado_por     VARCHAR(120)  NOT NULL,
    modificado_por VARCHAR(120)  NOT NULL,
    CONSTRAINT ck_historial_tipo CHECK (tipo IN ('CREACION', 'EDICION', 'CAMBIO_ESTADO', 'ELIMINACION', 'COMPARTICION')),
    CONSTRAINT ck_historial_elemento CHECK (elemento IN ('PROCESO', 'POOL', 'LANE', 'ACTIVIDAD', 'GATEWAY', 'EVENTO',
                                                          'ARCO', 'MENSAJE', 'CORRELACION', 'ROL_PROCESO')),
    CONSTRAINT fk_historial_empresa FOREIGN KEY (empresa_id) REFERENCES empresa (id),
    CONSTRAINT fk_historial_proceso FOREIGN KEY (proceso_id) REFERENCES proceso (id) ON DELETE CASCADE
);
CREATE INDEX idx_historial_proceso ON historial_cambio (proceso_id);
CREATE INDEX idx_historial_elemento ON historial_cambio (elemento, elemento_id);

CREATE TABLE pool (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    empresa_id         BIGINT       NOT NULL,
    proceso_id         BIGINT       NOT NULL,
    nombre             VARCHAR(120) NOT NULL,
    tipo               VARCHAR(20)  NOT NULL,
    caja_negra         BOOLEAN      NOT NULL,
    permiso_estructura VARCHAR(30)  NOT NULL,
    orden              INTEGER      NOT NULL,
    activo             BOOLEAN      NOT NULL,
    creado_en          TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    modificado_en      TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    creado_por         VARCHAR(120) NOT NULL,
    modificado_por     VARCHAR(120) NOT NULL,
    CONSTRAINT ck_pool_tipo CHECK (tipo IN ('PROPIETARIO', 'CLIENTE', 'PROVEEDOR', 'SISTEMA_EXTERNO')),
    CONSTRAINT ck_pool_permiso CHECK (permiso_estructura IN ('SOLO_ADMINISTRADOR', 'ADMINISTRADOR_Y_EDITOR')),
    CONSTRAINT fk_pool_empresa FOREIGN KEY (empresa_id) REFERENCES empresa (id),
    CONSTRAINT fk_pool_proceso FOREIGN KEY (proceso_id) REFERENCES proceso (id) ON DELETE CASCADE
);
CREATE INDEX idx_pool_proceso ON pool (proceso_id);

CREATE TABLE lane (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    empresa_id     BIGINT       NOT NULL,
    pool_id        BIGINT       NOT NULL,
    rol_proceso_id BIGINT       NOT NULL,
    orden          INTEGER      NOT NULL,
    activo         BOOLEAN      NOT NULL,
    creado_en      TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    modificado_en  TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    creado_por     VARCHAR(120) NOT NULL,
    modificado_por VARCHAR(120) NOT NULL,
    CONSTRAINT fk_lane_empresa FOREIGN KEY (empresa_id) REFERENCES empresa (id),
    CONSTRAINT fk_lane_pool FOREIGN KEY (pool_id) REFERENCES pool (id) ON DELETE CASCADE,
    -- Sin cascada: un rol de proceso en uso no se elimina (HU-19, HU-24)
    CONSTRAINT fk_lane_rol FOREIGN KEY (rol_proceso_id) REFERENCES rol_proceso (id)
);
CREATE INDEX idx_lane_pool ON lane (pool_id);
CREATE INDEX idx_lane_rol ON lane (rol_proceso_id);

CREATE TABLE nodo_flujo (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    empresa_id     BIGINT       NOT NULL,
    proceso_id     BIGINT       NOT NULL,
    pool_id        BIGINT       NOT NULL,
    lane_id        BIGINT,
    tipo           VARCHAR(20)  NOT NULL,
    nombre         VARCHAR(120),
    tipo_actividad VARCHAR(20),
    tipo_gateway   VARCHAR(20),
    variante       VARCHAR(20),
    pos_x          INTEGER      NOT NULL,
    pos_y          INTEGER      NOT NULL,
    activo         BOOLEAN      NOT NULL,
    version        BIGINT,
    creado_en      TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    modificado_en  TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    creado_por     VARCHAR(120) NOT NULL,
    modificado_por VARCHAR(120) NOT NULL,
    CONSTRAINT ck_nodo_tipo CHECK (tipo IN ('ACTIVIDAD', 'GATEWAY', 'EVENTO_INICIO', 'EVENTO_FIN',
                                            'MESSAGE_THROW', 'MESSAGE_CATCH')),
    CONSTRAINT ck_nodo_tipo_actividad CHECK (tipo_actividad IN ('TAREA', 'USUARIO', 'MANUAL', 'SERVICIO', 'ENVIO', 'RECEPCION')),
    CONSTRAINT ck_nodo_tipo_gateway CHECK (tipo_gateway IN ('EXCLUSIVO', 'PARALELO', 'INCLUSIVO')),
    CONSTRAINT ck_nodo_variante CHECK (variante IN ('INICIO', 'INTERMEDIO', 'FIN')),
    CONSTRAINT fk_nodo_empresa FOREIGN KEY (empresa_id) REFERENCES empresa (id),
    CONSTRAINT fk_nodo_proceso FOREIGN KEY (proceso_id) REFERENCES proceso (id) ON DELETE CASCADE,
    CONSTRAINT fk_nodo_pool FOREIGN KEY (pool_id) REFERENCES pool (id) ON DELETE CASCADE,
    CONSTRAINT fk_nodo_lane FOREIGN KEY (lane_id) REFERENCES lane (id) ON DELETE CASCADE
);
CREATE INDEX idx_nodo_proceso ON nodo_flujo (proceso_id);
CREATE INDEX idx_nodo_lane ON nodo_flujo (lane_id);

CREATE TABLE arco (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    empresa_id     BIGINT       NOT NULL,
    proceso_id     BIGINT       NOT NULL,
    origen_id      BIGINT       NOT NULL,
    destino_id     BIGINT       NOT NULL,
    etiqueta       VARCHAR(80),
    condicion      VARCHAR(200),
    activo         BOOLEAN      NOT NULL,
    creado_en      TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    modificado_en  TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    creado_por     VARCHAR(120) NOT NULL,
    modificado_por VARCHAR(120) NOT NULL,
    CONSTRAINT fk_arco_empresa FOREIGN KEY (empresa_id) REFERENCES empresa (id),
    CONSTRAINT fk_arco_proceso FOREIGN KEY (proceso_id) REFERENCES proceso (id) ON DELETE CASCADE,
    CONSTRAINT fk_arco_origen FOREIGN KEY (origen_id) REFERENCES nodo_flujo (id) ON DELETE CASCADE,
    CONSTRAINT fk_arco_destino FOREIGN KEY (destino_id) REFERENCES nodo_flujo (id) ON DELETE CASCADE
);
CREATE INDEX idx_arco_proceso ON arco (proceso_id);
CREATE INDEX idx_arco_origen ON arco (origen_id);
CREATE INDEX idx_arco_destino ON arco (destino_id);

CREATE TABLE mensaje (
    id                        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    empresa_id                BIGINT       NOT NULL,
    proceso_id                BIGINT       NOT NULL,
    nodo_id                   BIGINT       NOT NULL,
    direccion                 VARCHAR(20)  NOT NULL,
    nombre                    VARCHAR(120) NOT NULL,
    pool_destino_id           BIGINT,
    tipo_destino              VARCHAR(20),
    momento                   VARCHAR(300),
    politica_fallo            VARCHAR(30),
    actividad_manejo_error_id BIGINT,
    origen_externo            BOOLEAN      NOT NULL,
    clave_correlacion         VARCHAR(120),
    accion_sin_caso           VARCHAR(30),
    activo                    BOOLEAN      NOT NULL,
    creado_en                 TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    modificado_en             TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    creado_por                VARCHAR(120) NOT NULL,
    modificado_por            VARCHAR(120) NOT NULL,
    CONSTRAINT uk_mensaje_nodo UNIQUE (nodo_id),
    CONSTRAINT ck_mensaje_direccion CHECK (direccion IN ('ENVIO', 'RECEPCION')),
    CONSTRAINT ck_mensaje_tipo_destino CHECK (tipo_destino IN ('CORREO', 'SERVICIO_WEB', 'COLA')),
    CONSTRAINT ck_mensaje_politica_fallo CHECK (politica_fallo IN ('CONTINUAR', 'DERIVAR_A_ACTIVIDAD', 'FINALIZAR_PROCESO')),
    CONSTRAINT ck_mensaje_accion_sin_caso CHECK (accion_sin_caso IN ('DESCARTAR', 'INICIAR_CASO_NUEVO')),
    CONSTRAINT fk_mensaje_empresa FOREIGN KEY (empresa_id) REFERENCES empresa (id),
    CONSTRAINT fk_mensaje_proceso FOREIGN KEY (proceso_id) REFERENCES proceso (id) ON DELETE CASCADE,
    CONSTRAINT fk_mensaje_nodo FOREIGN KEY (nodo_id) REFERENCES nodo_flujo (id) ON DELETE CASCADE,
    CONSTRAINT fk_mensaje_pool_destino FOREIGN KEY (pool_destino_id) REFERENCES pool (id) ON DELETE CASCADE,
    CONSTRAINT fk_mensaje_manejo_error FOREIGN KEY (actividad_manejo_error_id) REFERENCES nodo_flujo (id) ON DELETE CASCADE
);
CREATE INDEX idx_mensaje_proceso ON mensaje (proceso_id);
CREATE INDEX idx_mensaje_pool_destino ON mensaje (pool_destino_id);

CREATE TABLE campo_mensaje (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    empresa_id     BIGINT       NOT NULL,
    mensaje_id     BIGINT       NOT NULL,
    nombre         VARCHAR(60)  NOT NULL,
    tipo_dato      VARCHAR(20)  NOT NULL,
    orden          INTEGER      NOT NULL,
    activo         BOOLEAN      NOT NULL,
    creado_en      TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    modificado_en  TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    creado_por     VARCHAR(120) NOT NULL,
    modificado_por VARCHAR(120) NOT NULL,
    CONSTRAINT ck_campo_tipo_dato CHECK (tipo_dato IN ('TEXTO', 'NUMERO', 'DECIMAL', 'FECHA', 'BOOLEANO')),
    CONSTRAINT fk_campo_empresa FOREIGN KEY (empresa_id) REFERENCES empresa (id),
    CONSTRAINT fk_campo_mensaje FOREIGN KEY (mensaje_id) REFERENCES mensaje (id) ON DELETE CASCADE
);

CREATE TABLE uso_datos_mensaje (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    empresa_id     BIGINT       NOT NULL,
    mensaje_id     BIGINT       NOT NULL,
    actividad_id   BIGINT       NOT NULL,
    activo         BOOLEAN      NOT NULL,
    creado_en      TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    modificado_en  TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    creado_por     VARCHAR(120) NOT NULL,
    modificado_por VARCHAR(120) NOT NULL,
    CONSTRAINT fk_uso_empresa FOREIGN KEY (empresa_id) REFERENCES empresa (id),
    CONSTRAINT fk_uso_mensaje FOREIGN KEY (mensaje_id) REFERENCES mensaje (id) ON DELETE CASCADE,
    CONSTRAINT fk_uso_actividad FOREIGN KEY (actividad_id) REFERENCES nodo_flujo (id) ON DELETE CASCADE
);
